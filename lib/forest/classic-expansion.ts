import { words } from './content';
type Scene = [english: string, korean: string, term: string, meaning: string, prop: string];
const retell = (
  id: string,
  title: string,
  englishTitle: string,
  difficulty: TaleDifficulty,
  genre: Tale['genre'],
  source: string,
  cast: string[],
  theme: SceneTheme,
  description: string,
  badge: string,
  scenes: Scene[],
  color: string,
): Tale => ({
  id,
  title,
  englishTitle,
  difficulty,
  genre,
  source,
  description,
  badge,
  color,
  pages: scenes.map(([english, korean, term, meaning, prop]) => ({
    english,
    korean,
    theme,
    cast,
    prop,
    caption: korean,
    vocabulary: { english: term, korean: meaning },
    wordId: words.find(
      (word) =>
        word.name === term && word.korean === meaning && english.toLowerCase().includes(term),
    )?.id,
  })),
});
