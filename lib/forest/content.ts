function storyCast(text: string): string {
  return text
    .replaceAll('곰은', '준호는')
    .replaceAll('곰이', '준호가')
    .replaceAll('곰을', '준호를')
    .replaceAll('곰의', '준호의')
    .replaceAll('곰에게', '준호에게')
    .replaceAll('곰과', '준호와')
    .replaceAll('곰 혼자', '혼자')
    .replaceAll('토끼는', '하린이는')
    .replaceAll('토끼가', '하린이가')
    .replaceAll('토끼를', '하린이를')
    .replaceAll('토끼의', '하린이의')
    .replaceAll('토끼 탐정', '어린이 탐정')
    .replaceAll('다람쥐는', '지우는')
    .replaceAll('다람쥐가', '지우가')
    .replaceAll('다람쥐의', '지우의')
    .replaceAll('다람쥐에게', '지우에게')
    .replaceAll('고슴도치는', '도윤이는')
    .replaceAll('고슴도치가', '도윤이가')
    .replaceAll('고슴도치도', '도윤이도')
    .replaceAll('고슴도치를', '도윤이를')
    .replaceAll('고양이는', '한서가')
    .replaceAll('고양이가', '한서가')
    .replaceAll('고양이와', '한서와')
    .replaceAll('고양이를', '한서를')
    .replaceAll('비버가', '목공 선생님이')
    .replaceAll('어른 비버의', '목공 선생님의');
}
